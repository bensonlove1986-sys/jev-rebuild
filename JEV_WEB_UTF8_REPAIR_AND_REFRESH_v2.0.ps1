}

# 日志函数
function Write-Log($message) {
    $timestamp = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
    $logEntry = "[$timestamp] $message"
    Add-Content -Path $repairLog -Value $logEntry -Encoding UTF8
    Write-Host $logEntry
}

