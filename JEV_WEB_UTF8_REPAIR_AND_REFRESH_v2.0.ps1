# 终止浏览器进程
function Stop-BrowserProcesses {
    Write-Log "开始终止浏览器进程..."
    foreach ($browser in $browserProcesses) {
        try {
            Get-Process -Name $browser -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue
            Write-Log "  - 已终止 $browser 进程"
        } catch {
            Write-Log "  - 终止 $browser 进程时出错: $_"
        }
    }
}

# 清理浏览器缓存
function Clear-BrowserCache {
    Write-Log "开始清理浏览器缓存..."
    
    # 清理Edge缓存
    $edgeCachePath = "$env:LOCALAPPDATA\Microsoft\Edge\User Data\Default\Cache"
    if (Test-Path $edgeCachePath) {
        try {
            Get-ChildItem -Path $edgeCachePath -Force -Recurse | Remove-Item -Force -Recurse -ErrorAction SilentlyContinue
            Write-Log "  - 已清理 Edge 缓存"
        } catch {
            Write-Log "  - 清理 Edge 缓存时出错: $_"
        }
    }
    
    # 清理Chrome缓存
    $chromeCachePath = "$env:LOCALAPPDATA\Google\Chrome\User Data\Default\Cache"
    if (Test-Path $chromeCachePath) {
        try {
            Get-ChildItem -Path $chromeCachePath -Force -Recurse | Remove-Item -Force -Recurse -ErrorAction SilentlyContinue
            Write-Log "  - 已清理 Chrome 缓存"
        } catch {
            Write-Log "  - 清理 Chrome 缓存时出错: $_"
        }
    }
    
    # 清理临时文件夹
    $tempPath = $env:TEMP
    if (Test-Path $tempPath) {
        try {
            Get-ChildItem -Path $tempPath -Force -Recurse -ErrorAction SilentlyContinue | Where-Object { -not $_.PSIsContainer -and (Get-Date).AddDays(-1) -gt $_.CreationTime } | Remove-Item -Force -ErrorAction SilentlyContinue
            Write-Log "  - 已清理临时文件夹中的旧文件"
        } catch {
            Write-Log "  - 清理临时文件夹时出错: $_"
        }
    }
}

# 重启浏览器并打开页面
function Start-BrowserAndOpenPages {
    Write-Log "开始重启浏览器并打开页面..."
    
    # 等待2秒确保缓存释放
    Write-Log "  - 等待2秒确保缓存释放..."
    Start-Sleep -Seconds 2
    
    # 尝试打开Chrome或Edge
    $browserPaths = @(
        "$env:PROGRAMFILES\Google\Chrome\Application\chrome.exe",
        "$env:PROGRAMFILES (x86)\Google\Chrome\Application\chrome.exe",
        "$env:PROGRAMFILES\Microsoft\Edge\Application\msedge.exe",
        "$env:PROGRAMFILES (x86)\Microsoft\Edge\Application\msedge.exe"
    )
    
    $browserFound = $false
    foreach ($path in $browserPaths) {
        if (Test-Path $path) {
            try {
                # 打开登录页面
                Start-Process -FilePath $path -ArgumentList "http://localhost:8080/ui/login_portal.html" -ErrorAction SilentlyContinue
                # 打开仪表盘页面
                Start-Process -FilePath $path -ArgumentList "http://localhost:8080/ui/sentinel_dashboard.html" -ErrorAction SilentlyContinue
                $browserFound = $true
                Write-Log "  - 已使用 $(Split-Path $path -Leaf) 打开页面"
                break
            } catch {
                Write-Log "  - 启动浏览器时出错: $_"
            }
        }
    }
    
    if (-not $browserFound) {
        Write-Log "  - 未找到Chrome或Edge浏览器，尝试使用默认浏览器"
        try {
            Start-Process -FilePath "http://localhost:8080/ui/login_portal.html"
            Start-Process -FilePath "http://localhost:8080/ui/sentinel_dashboard.html"
        } catch {
            Write-Log "  - 启动默认浏览器时出错: $_"
        }
    }
}

# 生成修复报告
function Generate-RepairSummary {
    try {
        $summary = @{
            'task_name' = 'JEV-WEB-UTF8-REPAIR-AND-REFRESH-v2.0';
            'timestamp' = Get-Date -Format "yyyy-MM-dd HH:mm:ss"; 
            'total_files' = $targetFiles.Count;
            'success_files' = ($repairStats.Values | Where-Object { $_.success }).Count;
            'failed_files' = ($repairStats.Values | Where-Object { -not $_.success }).Count;
            'total_repairs' = ($repairStats.Values | Measure-Object -Property repair_count -Sum).Sum;
            'file_details' = $repairStats;
            'cache_cleared' = $true;
            'browser_restarted' = $true;
            'status' = 'completed'
        }
        
        $summaryJson = $summary | ConvertTo-Json -Depth 4 -Encoding UTF8
        Set-Content -Path $summaryReport -Value $summaryJson -Encoding UTF8
        Write-Log "生成修复报告: $summaryReport"
    } catch {
        Write-Log "生成修复报告时出错: $_"
    }
}

# 主函数
function Main {
    # 确保日志目录存在
    Ensure-LogDirectory
    
    # 初始化日志
    "========== JEV-WEB-UTF8-REPAIR-AND-REFRESH-v2.0 开始执行 ==========" | Out-File -FilePath $repairLog -Encoding UTF8
    
    # 修复网页文件
    Write-Log "开始修复网页文件..."
    foreach ($file in $targetFiles) {
        Repair-WebFile $file
    }
    
    # 清理浏览器缓存和刷新
    Write-Log "开始缓存清理与页面刷新..."
    Stop-BrowserProcesses
    Clear-BrowserCache
    Start-BrowserAndOpenPages
    
    # 生成报告
    Generate-RepairSummary
    
    # 控制台输出完成信息
    Write-Host ""
    Write-Host "✅ login_portal.html 修复完成并刷新"
    Write-Host "✅ sentinel_dashboard.html 修复完成并刷新"
    Write-Host "🟢 全部网页缓存已清理并重新加载成功"
    Write-Host ""
    
    "========== JEV-WEB-UTF8-REPAIR-AND-REFRESH-v2.0 执行完成 ==========" | Add-Content -Path $repairLog -Encoding UTF8
}

