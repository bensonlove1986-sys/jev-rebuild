// 生成发票
async function generateInvoice(piData) {
  try {
    // 清理输入
    const sanitizedData = sanitizeInput(piData);
    
    // 验证PI号
    if (!sanitizedData.pi_no) {
      throw new Error('PI number is required to generate invoice');
    }
    
    // 生成发票编号
    const invoiceNo = generateInvoiceNumber(sanitizedData.pi_no);
    
    // 创建发票对象
    const invoiceData = {
      invoice_no: invoiceNo,
      pi_no: sanitizedData.pi_no,
      invoice_date: new Date().toISOString(),
      due_date: calculateDueDate(sanitizedData.paymentTerms || PI_CONFIG.base.DEFAULT_TERMS_DAYS),
      client: sanitizedData.client,
      items: sanitizedData.items || [],
      currency: sanitizedData.currency || PI_CONFIG.base.DEFAULT_CURRENCY,
      payment_terms: sanitizedData.paymentTerms || `${PI_CONFIG.base.DEFAULT_TERMS_DAYS} days`,
      payment_method: sanitizedData.paymentMethod || PI_CONFIG.base.DEFAULT_PAYMENT_METHOD,
      notes: sanitizedData.notes || 'Invoice generated from Proforma Invoice',
      status: 'unpaid',
      generated_from: 'pi',
      metadata: {
        generated_at: new Date().toISOString(),
        gateway_version: 'v2.0',
        module: 'pi_generator'
      }
    };
    
    // 计算总计
    const totals = await calculatePITotals(invoiceData);
    invoiceData.totals = totals;
    
    // 生成PDF链接
    invoiceData.link = await generateInvoicePdfLink(invoiceData);
    
    logMessage('INFO', 'Invoice generated successfully', { 
      invoice_no: invoiceData.invoice_no,
      pi_no: invoiceData.pi_no
    });
    
    // 返回标准化的发票对象
    return {
      invoice_no: invoiceData.invoice_no,
      pi_no: invoiceData.pi_no,
      client: invoiceData.client,
      items: invoiceData.items,
      total: invoiceData.totals.total,
      currency: invoiceData.currency,
      link: invoiceData.link,
      invoice_date: invoiceData.invoice_date,
      due_date: invoiceData.due_date,
      status: invoiceData.status,
      payment_terms: invoiceData.payment_terms,
      payment_method: invoiceData.payment_method
    };
  } catch (error) {
    logMessage('ERROR', 'Failed to generate invoice', { error: error.message });
    throw error;
  }
}

// 生成发票编号
function generateInvoiceNumber(piNo) {
  return `INV-${piNo.replace(/^PI-/, '')}`;
}

// 计算到期日期
function calculateDueDate(terms) {
  const days = typeof terms === 'number' ? terms : parseInt(terms);
  const date = new Date();
  date.setDate(date.getDate() + (isNaN(days) ? PI_CONFIG.base.DEFAULT_TERMS_DAYS : days));
  return date.toISOString();
}

// 生成发票PDF链接
async function generateInvoicePdfLink(invoiceData) {
  if (!PI_CONFIG.pdf.ENABLED) {
    return null;
  }
  
  try {
    // 模拟PDF生成
    await new Promise(resolve => setTimeout(resolve, 500));
    
    // 生成一个模拟的PDF链接
    const timestamp = Date.now();
    const pdfLink = `https://jevshop.workers.dev/api/pdf/invoice/${invoiceData.invoice_no}?timestamp=${timestamp}&token=${generatePdfToken(invoiceData)}`;
    
    logMessage('INFO', 'Invoice PDF generated successfully', { invoice_no: invoiceData.invoice_no });
    return pdfLink;
  } catch (error) {
    logMessage('ERROR', 'Failed to generate invoice PDF', { error: error.message });
    return null;
  }
}

// 批量生成PI
async function batchGeneratePI(orders) {
  try {
    if (!Array.isArray(orders)) {
      throw new Error('Orders must be an array');
    }
    
    if (orders.length === 0) {
      throw new Error('Orders array cannot be empty');
    }
    
    if (orders.length > 10) {
      throw new Error('Maximum 10 orders per batch');
    }
    
    const results = [];
    const errors = [];
    
    // 并行处理订单
    const promises = orders.map(async (order, index) => {
      try {
        const pi = await generatePI(order);
        results.push({ index, success: true, data: pi });
      } catch (error) {
        errors.push({ index, success: false, error: error.message });
        results.push({ index, success: false, error: error.message });
      }
    });
    
    // 等待所有处理完成
    await Promise.all(promises);
    
    logMessage('INFO', `Batch PI generation completed. Success: ${results.filter(r => r.success).length}, Failed: ${errors.length}`);
    
    return {
      success: errors.length === 0,
      total_orders: orders.length,
      successful: results.filter(r => r.success).length,
      failed: errors.length,
      results,
      errors
    };
  } catch (error) {
    logMessage('ERROR', 'Failed to batch generate PIs', { error: error.message });
    throw error;
  }
}

