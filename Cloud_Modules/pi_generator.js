// 生成PI编号
function generatePINumber(prefix = PI_CONFIG.base.PI_PREFIX) {
  const date = new Date();
  const year = date.getFullYear().toString();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  const random = Math.floor(Math.random() * 10000).toString().padStart(4, '0');
  
  return `${prefix}${year}${month}${day}-${random}`;
}

// 日志记录函数
function logMessage(level, message, details = {}) {
  if (!PI_CONFIG.logging.ENABLED) return;
  
  const timestamp = new Date().toISOString();
  const logEntry = {
    level,
    timestamp,
    message,
    details: PI_CONFIG.logging.INCLUDE_SENSITIVE_DATA ? details : {}
  };
  
  // 根据日志级别过滤
  const levelOrder = { 'DEBUG': 0, 'INFO': 1, 'WARN': 2, 'ERROR': 3, 'FATAL': 4 };
  const currentLevel = levelOrder[PI_CONFIG.logging.LOG_LEVEL] || 1;
  
  if (levelOrder[level] >= currentLevel) {
    // 输出到控制台
    switch (level) {
      case 'DEBUG':
        console.debug(`[pi_generator] ${JSON.stringify(logEntry)}`);
        break;
      case 'INFO':
        console.info(`[pi_generator] ${JSON.stringify(logEntry)}`);
        break;
      case 'WARN':
        console.warn(`[pi_generator] ${JSON.stringify(logEntry)}`);
        break;
      case 'ERROR':
      case 'FATAL':
        console.error(`[pi_generator] ${JSON.stringify(logEntry)}`);
        break;
    }
  }
}

// 清理过期请求计数
function cleanupRequestCounts() {
  const now = Date.now();
  for (const [key, value] of memoryCache.requestCounts.entries()) {
    if (now - value.timestamp > 60000) { // 1分钟过期
      memoryCache.requestCounts.delete(key);
    }
  }
}

// 速率限制检查
function checkRateLimit(clientId) {
  if (!PI_CONFIG.security.RATE_LIMIT_ENABLED) return { allowed: true };
  
  // 清理过期计数
  cleanupRequestCounts();
  
  const now = Date.now();
  let count = 0;
  let timestamp = now;
  
  if (memoryCache.requestCounts.has(clientId)) {
    const data = memoryCache.requestCounts.get(clientId);
    count = data.count;
    timestamp = data.timestamp;
  }
  
  // 检查是否超过限制
  if (count >= PI_CONFIG.security.MAX_REQUESTS_PER_MINUTE) {
    return {
      allowed: false,
      reason: `Rate limit exceeded. Maximum ${PI_CONFIG.security.MAX_REQUESTS_PER_MINUTE} requests per minute.`,
      retryAfter: Math.ceil((timestamp + 60000 - now) / 1000)
    };
  }
  
  // 更新计数
  memoryCache.requestCounts.set(clientId, {
    count: count + 1,
    timestamp: now
  });
  
  return { allowed: true, count: count + 1 };
}

// 清理输入数据
function sanitizeInput(input) {
  if (!PI_CONFIG.security.SANITIZE_INPUT) return input;
  
  if (typeof input === 'string') {
    // 移除潜在的危险字符
    return input.replace(/[<>'"&]/g, (char) => {
      const entityMap = {
        '<': '&lt;',
        '>': '&gt;',
        "'": '&#39;',
        '"': '&quot;',
        '&': '&amp;'
      };
      return entityMap[char] || char;
    });
  } else if (typeof input === 'object' && input !== null) {
    // 递归清理对象
    if (Array.isArray(input)) {
      return input.map(item => sanitizeInput(item));
    } else {
      const sanitized = {};
      for (const [key, value] of Object.entries(input)) {
        // 不清理特定字段
        if (key === 'amount' || key === 'quantity' || key === 'unitPrice') {
          sanitized[key] = value;
        } else {
          sanitized[key] = sanitizeInput(value);
        }
      }
      return sanitized;
    }
  }
  
  return input;
}

// 获取汇率
async function getExchangeRate(fromCurrency, toCurrency) {
  // 如果是同一种货币，汇率为1
  if (fromCurrency === toCurrency) {
    return 1;
  }
  
  // 检查缓存是否有效
  const now = Date.now();
  if (memoryCache.exchangeRates.data && 
      (now - memoryCache.exchangeRates.timestamp) < PI_CONFIG.exchange.CACHE_TTL_MS) {
    if (memoryCache.exchangeRates.data[fromCurrency] && 
        memoryCache.exchangeRates.data[fromCurrency][toCurrency]) {
      return memoryCache.exchangeRates.data[fromCurrency][toCurrency];
    }
  }
  
  // 尝试从API获取（模拟）
  try {
    if (PI_CONFIG.exchange.ENABLE_AUTO_EXCHANGE) {
      // 这里应该调用真实的汇率API
      // const response = await fetch(PI_CONFIG.exchange.EXCHANGE_API_URL);
      // const rates = await response.json();
      
      // 模拟API调用延迟
      await new Promise(resolve => setTimeout(resolve, 100));
      
      // 使用默认汇率
      const rates = PI_CONFIG.exchange.DEFAULT_EXCHANGE_RATES;
      
      // 更新缓存
      memoryCache.exchangeRates = {
        data: rates,
        timestamp: now
      };
      
      if (rates[fromCurrency] && rates[fromCurrency][toCurrency]) {
        return rates[fromCurrency][toCurrency];
      }
    }
  } catch (error) {
    logMessage('ERROR', 'Failed to fetch exchange rates', { error: error.message });
  }
  
  // 回退到默认汇率
  if (PI_CONFIG.exchange.DEFAULT_EXCHANGE_RATES[fromCurrency] && 
      PI_CONFIG.exchange.DEFAULT_EXCHANGE_RATES[fromCurrency][toCurrency]) {
    return PI_CONFIG.exchange.DEFAULT_EXCHANGE_RATES[fromCurrency][toCurrency];
  }
  
  throw new Error(`Exchange rate not available for ${fromCurrency} to ${toCurrency}`);
}

// 货币转换
async function convertCurrency(amount, fromCurrency, toCurrency) {
  if (amount === null || amount === undefined) {
    throw new Error('Amount is required');
  }
  
  const rate = await getExchangeRate(fromCurrency, toCurrency);
  const converted = amount * rate;
  
  // 格式化到指定小数位
  return parseFloat(converted.toFixed(PI_CONFIG.formatting.DECIMAL_PLACES));
}

// 格式化金额
function formatAmount(amount, currency) {
  const formatter = new Intl.NumberFormat('en-US', {
    minimumFractionDigits: PI_CONFIG.formatting.DECIMAL_PLACES,
    maximumFractionDigits: PI_CONFIG.formatting.DECIMAL_PLACES,
    useGrouping: true
  });
  
  const formatted = formatter.format(amount);
  const symbol = PI_CONFIG.formatting.CURRENCY_SYMBOLS[currency] || currency;
  
  return `${symbol}${formatted}`;
}

// 验证PI数据
function validatePIData(piData) {
  if (!PI_CONFIG.security.ENABLE_VALIDATION) return { valid: true };
  
  try {
    // 检查必需字段
    for (const field of PI_CONFIG.validation.REQUIRED_FIELDS) {
      if (!piData[field]) {
        throw new Error(`Missing required field: ${field}`);
      }
    }
    
    // 验证客户端信息
    const client = piData.client;
    for (const field of PI_CONFIG.validation.CLIENT_REQUIRED_FIELDS) {
      if (!client[field] || client[field].toString().trim() === '') {
        throw new Error(`Client ${field} is required`);
      }
    }
    
    // 验证邮箱格式
    const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailRegex.test(client.email)) {
      throw new Error('Invalid client email format');
    }
    
    // 验证商品列表
    const items = piData.items;
    if (!Array.isArray(items) || items.length === 0) {
      throw new Error('Items must be a non-empty array');
    }
    
    if (items.length > PI_CONFIG.base.MAX_ITEMS_PER_PI) {
      throw new Error(`Maximum ${PI_CONFIG.base.MAX_ITEMS_PER_PI} items per PI`);
    }
    
    // 验证每个商品
    for (let i = 0; i < items.length; i++) {
      const item = items[i];
      for (const field of PI_CONFIG.validation.ITEM_REQUIRED_FIELDS) {
        if (!item[field]) {
          throw new Error(`Item ${i + 1} missing ${field}`);
        }
      }
      
      // 验证数量
      if (typeof item.quantity !== 'number' || 
          item.quantity < PI_CONFIG.validation.MIN_ITEM_QUANTITY ||
          !Number.isInteger(item.quantity)) {
        throw new Error(`Item ${i + 1} quantity must be a positive integer`);
      }
      
      // 验证单价
      if (typeof item.unitPrice !== 'number' || 
          item.unitPrice < PI_CONFIG.validation.MIN_ITEM_PRICE ||
          item.unitPrice > PI_CONFIG.validation.MAX_ITEM_PRICE) {
        throw new Error(`Item ${i + 1} unit price out of range`);
      }
      
      // 验证币种
      if (!PI_CONFIG.base.SUPPORTED_CURRENCIES.includes(item.currency)) {
        throw new Error(`Unsupported currency: ${item.currency}`);
      }
    }
    
    // 验证币种
    if (!PI_CONFIG.base.SUPPORTED_CURRENCIES.includes(piData.currency)) {
      throw new Error(`Unsupported currency: ${piData.currency}`);
    }
    
    // 验证折扣
    if (piData.discountRate && 
        (typeof piData.discountRate !== 'number' || 
         piData.discountRate < 0 || 
         piData.discountRate > PI_CONFIG.validation.MAX_DISCOUNT_PERCENTAGE)) {
      throw new Error(`Discount rate must be between 0 and ${PI_CONFIG.validation.MAX_DISCOUNT_PERCENTAGE}`);
    }
    
    // 验证增值税
    if (piData.vatRate && 
        (typeof piData.vatRate !== 'number' || 
         piData.vatRate < 0 || 
         piData.vatRate > PI_CONFIG.validation.MAX_VAT_PERCENTAGE)) {
      throw new Error(`VAT rate must be between 0 and ${PI_CONFIG.validation.MAX_VAT_PERCENTAGE}`);
    }
    
    return { valid: true };
  } catch (error) {
    return { valid: false, error: error.message };
  }
}

// 计算PI总计
async function calculatePITotals(piData) {
  const totals = {
    subtotal: 0,
    discount: 0,
    vat: 0,
    total: 0,
    currency: piData.currency,
    itemsTotal: 0,
    itemCount: piData.items.length
  };
  
  // 计算每个商品的小计
  for (const item of piData.items) {
    let itemTotal = item.quantity * item.unitPrice;
    
    // 转换到PI币种
    if (item.currency !== piData.currency) {
      itemTotal = await convertCurrency(itemTotal, item.currency, piData.currency);
    }
    
    // 添加到总计
    totals.subtotal += itemTotal;
    totals.itemsTotal += itemTotal;
  }
  
  // 应用折扣
  const discountRate = piData.discountRate || PI_CONFIG.base.DEFAULT_DISCOUNT_RATE;
  totals.discount = (totals.subtotal * discountRate) / 100;
  
  // 计算折扣后的金额
  const amountAfterDiscount = totals.subtotal - totals.discount;
  
  // 应用增值税
  const vatRate = piData.vatRate || PI_CONFIG.base.DEFAULT_VAT_RATE;
  totals.vat = (amountAfterDiscount * vatRate) / 100;
  
  // 计算最终总计
  totals.total = amountAfterDiscount + totals.vat;
  
  // 格式化金额
  totals.subtotal = parseFloat(totals.subtotal.toFixed(PI_CONFIG.formatting.DECIMAL_PLACES));
  totals.discount = parseFloat(totals.discount.toFixed(PI_CONFIG.formatting.DECIMAL_PLACES));
  totals.vat = parseFloat(totals.vat.toFixed(PI_CONFIG.formatting.DECIMAL_PLACES));
  totals.total = parseFloat(totals.total.toFixed(PI_CONFIG.formatting.DECIMAL_PLACES));
  totals.itemsTotal = parseFloat(totals.itemsTotal.toFixed(PI_CONFIG.formatting.DECIMAL_PLACES));
  
  return totals;
}

