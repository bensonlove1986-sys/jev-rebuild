// 生成PDF令牌
function generatePdfToken(piData) {
  // 这是一个简单的令牌生成，实际应用中应该使用更安全的方法
  const data = `${piData.pi_no}-${piData.client.email}-${Date.now()}`;
  let hash = 0;
  for (let i = 0; i < data.length; i++) {
    const char = data.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32bit integer
  }
  return Math.abs(hash).toString(36).substr(0, 8);
}

// 生成PI
async function generatePI(orderData) {
  try {
    // 速率限制检查
    const clientId = orderData.client?.email || 'unknown';
    const rateLimitCheck = checkRateLimit(clientId);
    if (!rateLimitCheck.allowed) {
      throw new Error(rateLimitCheck.reason);
    }
    
    // 清理输入
    const sanitizedData = sanitizeInput(orderData);
    
    // 验证数据
    const validation = validatePIData(sanitizedData);
    if (!validation.valid) {
      throw new Error(validation.error);
    }
    
    // 检查客户端PI数量限制
    if (PI_CONFIG.security.MAX_PI_PER_CLIENT) {
      const clientCount = memoryCache.clientPICounts.get(clientId) || 0;
      if (clientCount >= PI_CONFIG.security.MAX_PI_PER_CLIENT) {
        throw new Error(`Client has reached maximum number of PIs: ${PI_CONFIG.security.MAX_PI_PER_CLIENT}`);
      }
    }
    
    // 生成PI编号
    const piNo = generatePINumber(sanitizedData.piPrefix || PI_CONFIG.base.PI_PREFIX);
    
    // 创建PI对象
    const piData = {
      pi_no: piNo,
      pi_date: new Date().toISOString(),
      expiry_date: sanitizedData.expiryDate || calculateExpiryDate(),
      client: sanitizedData.client,
      items: sanitizedData.items,
      currency: sanitizedData.currency || PI_CONFIG.base.DEFAULT_CURRENCY,
      incoterms: sanitizedData.incoterms || PI_CONFIG.base.DEFAULT_INCOTERMS,
      payment_terms: sanitizedData.paymentTerms || `${PI_CONFIG.base.DEFAULT_TERMS_DAYS} days`,
      payment_method: sanitizedData.paymentMethod || PI_CONFIG.base.DEFAULT_PAYMENT_METHOD,
      delivery_time: sanitizedData.deliveryTime || `${PI_CONFIG.base.DEFAULT_DELIVERY_TIME_DAYS} days`,
      discount_rate: sanitizedData.discountRate || 0,
      vat_rate: sanitizedData.vatRate || 0,
      notes: sanitizedData.notes || '',
      created_by: sanitizedData.createdBy || 'system',
      template: sanitizedData.template || PI_CONFIG.templates.DEFAULT_TEMPLATE,
      status: 'draft',
      metadata: {
        generated_at: new Date().toISOString(),
        gateway_version: 'v2.0',
        module: 'pi_generator'
      }
    };
    
    // 计算总计
    const totals = await calculatePITotals(piData);
    piData.totals = totals;
    
    // 生成PDF链接
    piData.link = await generatePdfLink(piData);
    
    // 更新客户端PI计数
    const clientCount = memoryCache.clientPICounts.get(clientId) || 0;
    memoryCache.clientPICounts.set(clientId, clientCount + 1);
    
    // 记录到最近的PI列表
    memoryCache.recentPIs.unshift({
      pi_no: piData.pi_no,
      client_name: piData.client.name,
      total: piData.totals.total,
      currency: piData.currency,
      created_at: piData.pi_date
    });
    
    // 保持列表大小
    if (memoryCache.recentPIs.length > 100) {
      memoryCache.recentPIs.pop();
    }
    
    logMessage('INFO', 'PI generated successfully', { 
      pi_no: piData.pi_no,
      client_name: piData.client.name,
      total: piData.totals.total
    });
    
    // 返回标准化的PI对象
    return {
      pi_no: piData.pi_no,
      client: piData.client,
      items: piData.items,
      total: piData.totals.total,
      currency: piData.currency,
      link: piData.link,
      pi_date: piData.pi_date,
      expiry_date: piData.expiry_date,
      status: piData.status,
      payment_terms: piData.payment_terms,
      payment_method: piData.payment_method,
      delivery_time: piData.delivery_time,
      incoterms: piData.incoterms,
      discount_rate: piData.discount_rate,
      vat_rate: piData.vat_rate,
      subtotal: piData.totals.subtotal,
      discount: piData.totals.discount,
      vat: piData.totals.vat,
      item_count: piData.totals.itemCount
    };
  } catch (error) {
    logMessage('ERROR', 'Failed to generate PI', { error: error.message });
    throw error;
  }
}

// 计算到期日期
function calculateExpiryDate(days = PI_CONFIG.base.DEFAULT_EXPIRY_DAYS) {
  const date = new Date();
  date.setDate(date.getDate() + days);
  return date.toISOString();
}

